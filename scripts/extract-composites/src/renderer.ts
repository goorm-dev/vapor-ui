import type { Item, Section } from './types.ts';

export interface RenderInput {
    slug: string;
    name: string;
    description?: string;
    sections: Record<string, Section>;
    liveExampleTicket: string;
}

const SECTION_ORDER = ['anatomy', 'examples', 'doDont', 'pattern', 'guidelines'] as const;

export function renderMdx(input: RenderInput): string {
    const parts: string[] = [];

    parts.push(renderFrontmatter(input));
    parts.push(renderAutoGeneratedHeader());

    for (const key of SECTION_ORDER) {
        const section = input.sections[key];
        if (!section) continue;
        const body = renderSection(key, section, input);
        if (body) parts.push(body);
    }

    for (const [key, section] of Object.entries(input.sections)) {
        if ((SECTION_ORDER as readonly string[]).includes(key)) continue;
        const body = renderSection(key, section, input);
        if (body) parts.push(body);
    }

    return parts.join('\n\n').trimEnd() + '\n';
}

function renderFrontmatter(input: RenderInput): string {
    const lines = ['---', `title: '${escapeYaml(input.name)}'`];
    if (input.description) {
        lines.push(`description: '${escapeYaml(input.description)}'`);
    }
    lines.push('---');
    return lines.join('\n');
}

function renderAutoGeneratedHeader(): string {
    return [
        '{/* AUTO-GENERATED — DO NOT EDIT. */}',
        '{/* Regenerate: pnpm -C scripts/extract-composites extract "<figma-url>" */}',
    ].join('\n');
}

function renderSection(key: string, section: Section, ctx: RenderInput): string {
    const heading = `## ${section.title}`;
    const body = renderSectionBody(key, section, ctx);
    if (!body) return `${heading}`;
    return `${heading}\n\n${body}`;
}

function renderSectionBody(key: string, section: Section, ctx: RenderInput): string {
    switch (key) {
        case 'anatomy':
            return renderAnatomy(section, ctx);
        case 'examples':
            return renderExamples(section, ctx);
        case 'doDont':
            return renderDoDont(section, ctx);
        default:
            return renderGeneric(key, section, ctx);
    }
}

function renderAnatomy(section: Section, ctx: RenderInput): string {
    const parts: string[] = [];
    if (section.image) {
        parts.push(
            `<DocsImage\n    src="${toPublicPath(ctx.slug, section.image)}"\n    alt="${escapeAttr(ctx.name)} anatomy"\n/>`,
        );
    }
    const rows = section.items
        .filter((it) => it.name)
        .map((it, idx) => {
            const label = `**${it.name}**`;
            return `${idx + 1}. ${label}${it.optional ? ' — Optional' : ''}`;
        });
    if (rows.length > 0) parts.push(rows.join('\n'));
    return parts.join('\n\n');
}

function renderExamples(section: Section, ctx: RenderInput): string {
    const parts: string[] = [];
    for (const item of section.items) {
        const subtitle = item.subtitle?.trim();
        if (subtitle) parts.push(`### ${subtitle}`);
        const desc = item.description?.trim();
        if (desc) parts.push(desc);
        parts.push(
            `{/* TODO(${ctx.liveExampleTicket}): replace fallback with live Preview */}\n<div className="rounded-v-300 bg-v-canvas-200 h-56 not-prose my-v-300" />`,
        );
    }
    return parts.join('\n\n');
}

function renderDoDont(section: Section, ctx: RenderInput): string {
    const parts: string[] = [];
    for (const item of section.items) {
        const subtitle = item.subtitle?.trim();
        if (subtitle) parts.push(`### ${subtitle}`);
        const grid = renderDoDontGrid(item, ctx);
        if (grid) parts.push(grid);
    }
    return parts.join('\n\n');
}

function renderDoDontGrid(item: Item, ctx: RenderInput): string | undefined {
    if (!item.do && !item.dont) return undefined;
    const lines = ['<DocsGrid cols={2}>'];
    if (item.do) {
        lines.push(
            `    <DoImage\n        src="${toPublicPath(ctx.slug, item.do.image)}"\n        alt="${escapeAttr(item.do.caption ?? '')}"\n        caption="${escapeAttr(item.do.caption ?? '')}"\n    />`,
        );
    }
    if (item.dont) {
        lines.push(
            `    <DontImage\n        src="${toPublicPath(ctx.slug, item.dont.image)}"\n        alt="${escapeAttr(item.dont.caption ?? '')}"\n        caption="${escapeAttr(item.dont.caption ?? '')}"\n    />`,
        );
    }
    lines.push('</DocsGrid>');
    return lines.join('\n');
}

function renderGeneric(key: string, section: Section, ctx: RenderInput): string {
    const parts: string[] = [];
    for (const item of section.items) {
        const subtitle = item.subtitle?.trim();
        if (subtitle) parts.push(`### ${subtitle}`);
        const desc = item.description?.trim();
        if (desc) parts.push(renderBulletsOrParagraph(desc));
        if (item.image) {
            parts.push(
                `<DocsImage src="${toPublicPath(ctx.slug, item.image)}" alt="${escapeAttr(subtitle ?? key)}" />`,
            );
        }
    }
    return parts.join('\n\n');
}

function renderBulletsOrParagraph(text: string): string {
    const lines = text.split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
    if (lines.length <= 1) return lines[0] ?? '';
    return lines.map((l) => (l.startsWith('- ') ? l : `- ${l}`)).join('\n');
}

function toPublicPath(slug: string, relPath: string): string {
    const normalized = relPath.replace(/^\/+/, '');
    return `/composites/${slug}/${normalized}`;
}

function escapeYaml(value: string): string {
    return value.replace(/'/g, "''");
}

function escapeAttr(value: string): string {
    return value.replace(/"/g, '&quot;');
}
