#!/usr/bin/env node
/**
 * Scan every MDX file under `content/` for `<Demo file="…" />` references and emit a
 * static import map at `src/components/demo/_examples.generated.ts`. The map replaces a
 * dynamic `import(template)` call so bundlers (both webpack and Turbopack) only bundle the
 * example files that are actually referenced, instead of walking the whole app tree.
 *
 * Re-run after adding or removing a Demo reference. The `postinstall` and `predev`/`prebuild`
 * hooks in `package.json` keep the manifest in sync automatically for typical workflows.
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const APP_ROOT = path.resolve(__dirname, '..');
const CONTENT_ROOT = path.join(APP_ROOT, 'content');
const OUTPUT_FILE = path.join(APP_ROOT, 'src/components/demo/_examples.generated.ts');

/** Normalise an authored `file` prop (e.g. `/content/docs/.../button.tsx`) into the key
 *  the Preview component looks up at runtime. We keep the leading slash so authored MDX
 *  and the manifest key share the exact same string. */
const toKey = (file) => (file.startsWith('/') ? file : `/${file.replace(/^\.\//, '')}`);

/** Build the path the manifest file uses in its static `import()` expression, resolved
 *  from the manifest's own location (`src/components/demo/`). TypeScript rejects explicit
 *  `.tsx` extensions in import specifiers without `allowImportingTsExtensions`, and the
 *  bundler resolves extensions on its own, so we strip the extension here. */
const toImportSpec = (file) => {
    const normalized = file.replace(/^\.?\//, '').replace(/\.tsx?$/, '');
    return `../../../${normalized}`;
};

async function* walk(dir) {
    for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
        const res = path.join(dir, entry.name);
        if (entry.isDirectory()) yield* walk(res);
        else if (
            entry.isFile() &&
            (entry.name.endsWith('.mdx') || entry.name.endsWith('.md'))
        )
            yield res;
    }
}

const FILE_ATTR = /\bfile=(["'])([^"']+\.tsx)\1/g;

async function collectReferences() {
    const refs = new Set();
    for await (const file of walk(CONTENT_ROOT)) {
        const source = await fs.readFile(file, 'utf-8');
        let match;
        FILE_ATTR.lastIndex = 0;
        while ((match = FILE_ATTR.exec(source)) !== null) {
            refs.add(match[2]);
        }
    }
    return [...refs].sort();
}

function renderManifest(references) {
    const lines = [
        '// AUTO-GENERATED by scripts/gen-demo-manifest.mjs — do not edit by hand.',
        '// Run `node scripts/gen-demo-manifest.mjs` from apps/website/ to refresh.',
        "import type { ComponentType } from 'react';",
        '',
        'type Loader = () => Promise<{ default: ComponentType }>;',
        '',
        'export const EXAMPLE_LOADERS: Record<string, Loader> = {',
    ];
    for (const ref of references) {
        const key = toKey(ref);
        const spec = toImportSpec(ref);
        lines.push(`    ${JSON.stringify(key)}: () => import(${JSON.stringify(spec)}),`);
    }
    lines.push('};');
    lines.push('');
    return lines.join('\n');
}

const refs = await collectReferences();
const manifest = renderManifest(refs);
await fs.mkdir(path.dirname(OUTPUT_FILE), { recursive: true });
await fs.writeFile(OUTPUT_FILE, manifest);
console.log(`[demo-manifest] wrote ${refs.length} entries → ${path.relative(APP_ROOT, OUTPUT_FILE)}`);
